# frozen_string_literal: true

require "digest"
require "yaml"
require "pathname"

# Mechanical parity between the mirrored ISO and OIML STS transformer trees
# (metanorma/metanorma-iso#1760, option 2).
#
# Both repos carry an identical copy of this file, of
# spec/sts/sts_sibling_parity_spec.rb and of spec/sts/sts_sibling_parity.yml.
# The manifest records, per file under lib/metanorma/<flavour>/sts, the
# SHA-256 of the file after namespace normalisation (Iso/Oiml/ISO/OIML/iso/oiml
# collapse to one token), as it stood at the last sync.
#
# Sync checklist when an engine file changes in either repo:
#   1. Port the change to the sibling tree (or decide it is flavour-only).
#   2. Run in each repo:
#        ruby spec/support/sts_sibling_parity.rb --write <sibling repo root>
#      and commit the regenerated spec/sts/sts_sibling_parity.yml in BOTH.
#   3. Both PRs reference each other.
module StsSiblingParity
  FLAVOURS = %w[iso oiml].freeze
  MANIFEST = "spec/sts/sts_sibling_parity.yml"

  module_function

  def own_flavour(root)
    FLAVOURS.find { |f| File.directory?(File.join(root, "lib/metanorma/#{f}/sts")) } ||
      raise("no lib/metanorma/{iso,oiml}/sts under #{root}")
  end

  def tree_dir(root, flavour)
    File.join(root, "lib/metanorma/#{flavour}/sts")
  end

  def normalise(bytes)
    # Windows checkouts may convert LF to CRLF; the digest must not depend on it.
    bytes.b.gsub("\r\n", "\n").gsub(/oiml|iso/i) do |m|
      case m
      when "oiml", "iso" then "flv"
      when "OIML", "ISO" then "FLV"
      else "Flv"
      end
    end
  end

  # { "relative/path" => sha256 of the normalised bytes }
  def digests(root, flavour)
    dir = Pathname.new(tree_dir(root, flavour))
    dir.glob("**/*").select(&:file?).to_h do |f|
      [f.relative_path_from(dir).to_s, Digest::SHA256.hexdigest(normalise(f.binread))]
    end.sort.to_h
  end

  def manifest(root)
    YAML.safe_load_file(File.join(root, MANIFEST))["files"]
  end

  # Paths whose manifest digest for +flavour+ disagrees with the tree on disk.
  def drift(root, flavour, expected)
    actual = digests(root, flavour)
    (expected.keys | actual.keys).sort.filter_map do |path|
      want = expected.dig(path, flavour)
      got = actual[path]
      next if want == got

      "#{path}: #{drift_kind(want, got)}"
    end
  end

  def drift_kind(want, got)
    return "removed" if got.nil?

    want.nil? ? "added" : "changed"
  end

  def build(roots)
    paths = roots.flat_map { |f, r| digests(r, f).keys }.uniq.sort
    files = paths.to_h do |p|
      [p, roots.to_h { |f, r| [f, digests(r, f)[p]] }]
    end
    { "files" => files }
  end

  def write(own_root, sibling_root)
    roots = { own_flavour(own_root) => own_root, own_flavour(sibling_root) => sibling_root }
    unless roots.keys.sort == FLAVOURS
      raise "need one iso and one oiml repo"
    end

    header = "# Generated by spec/support/sts_sibling_parity.rb --write; see its header.\n"
    yaml = header + build(roots).to_yaml
    [own_root, sibling_root].each { |r| File.write(File.join(r, MANIFEST), yaml) }
  end
end

if $PROGRAM_NAME == __FILE__ && ARGV.first == "--write"
  StsSiblingParity.write(File.expand_path("../..", __dir__), File.expand_path(ARGV[1]))
end
